import fs from 'node:fs/promises';
import path from 'node:path';

const directory='src/lib/motion-core/vendor/agent-icons';
const read=name=>fs.readFile(path.join(directory,name),'utf8');
function nested(svg){
 const root=svg.match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
 if(!root)throw new Error('Expected a standalone SVG');
 const viewBox=root[1].match(/viewBox="([^"]+)"/)?.[1];
 if(!viewBox)throw new Error('Expected an explicit SVG viewBox');
 const attributes=root[1].replace(/\s(?:xmlns|height|width|style|viewBox)="[^"]*"/g,'');
 const body=root[2].trim().replace(/\s+/g,' ');
 return `<svg x="0" y="0" width="64" height="64" viewBox="${viewBox}"${attributes}>${body}</svg>`;
}
const codex=await read('codex-color.svg');
const paths=[...codex.matchAll(/<path\b[^>]*>[\s\S]*?<\/path>/g)].map(match=>match[0]);
if(paths.length!==2||!paths[0].includes('fill="#fff"')||!paths[1].includes('fill="url('))throw new Error('Pinned Codex icon structure changed');
// The supplied colour icon includes an app tile. Keep the original cloud path
// and gradient, remove that tile, and give the cloud the same sticker outline
// as the three SVGs used in the reference page.
const cloud=paths[1].replaceAll('lobe-icons-codex-_R_0_','$id-codex');
const outline=cloud.replace(/fill="url\([^"]+\)"/,'fill="white" stroke="white" stroke-width="2.25" stroke-linejoin="round"');
const defs=codex.match(/<defs>[\s\S]*?<\/defs>/)?.[0].replaceAll('lobe-icons-codex-_R_0_','$id-codex');
if(!defs)throw new Error('Pinned Codex gradient missing');
const icons={
 chatgpt:nested(`<svg viewBox="1.5 1.5 21 21"><title>Codex</title>${outline}${cloud}${defs}</svg>`),
 claude:nested(await read('claude-color.svg')),
 cursor:nested(await read('cursor.svg')),
 grok:nested(await read('grok-bot.svg')),
};
await fs.writeFile('src/data/inline-agent-icons.mjs',`// Generated by scripts/import-inline-agent-icons.mjs from pinned SVG assets.\n// Lobe Icons: Copyright (c) 2023 LobeHub, MIT. See src/lib/motion-core/vendor/agent-icons/LICENSE and SOURCE.md.\nexport const INLINE_AGENT_ICONS=${JSON.stringify(icons,null,2)};\n`);
console.log('Imported four existing agent SVGs; no icon paths were redrawn.');
