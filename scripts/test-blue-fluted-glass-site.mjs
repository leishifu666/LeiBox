import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium, expect } from 'playwright/test';

const base = process.env.BASE_URL || 'http://127.0.0.1:3000';
const out = 'outputs/sashabirukoff-2113002960892649916';
const slug = 'blue-fluted-glass';
const href = `/docs/animations/${slug}`;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(base + '/components', { waitUntil: 'networkidle' });
  const card = page.locator(`[data-component-card="${href}"]`);
  const preview = card.locator(`[data-motion-preview="${slug}"]`);
  await expect(card.locator('h2')).toHaveText('蓝色棱纹流动背景');
  await card.scrollIntoViewIfNeeded();
  await page.mouse.move(1400, 20);
  await expect(preview).toHaveAttribute('data-preview-state', 'poster');
  await card.hover();
  await expect(preview.locator('[data-scene-ready=true]')).toHaveCount(1);
  assert.equal(await page.locator('[data-preview-state="playing"]').count(), 1);
  const frame = page.frameLocator(`[data-component-card="${href}"] iframe`);
  const canvas = frame.locator('.bfg-canvas');
  const before = await canvas.evaluate(n => n.toDataURL());
  await page.waitForTimeout(250);
  assert(await canvas.evaluate(n => n.toDataURL()) !== before, 'gallery hover is animated');
  assert.equal(await frame.locator('.bfg-stage').getAttribute('data-renderer'), 'webgl');
  await card.screenshot({ path: `${out}/gallery-hover.png` });
  await page.mouse.move(1400, 20);
  await expect(preview.locator('iframe')).toHaveCount(0);
  await card.locator('a').focus();
  await expect(preview.locator('iframe')).toHaveCount(1);
  await page.keyboard.press('Tab');
  await expect(preview.locator('iframe')).toHaveCount(0);
  await Promise.all([
    page.waitForURL(base + href, { timeout: 30000 }),
    card.locator('a').click(),
  ]);
  assert.equal(await page.locator('video').count(), 0);
  await expect(page.locator('a[href="https://x.com/sashabirukoff"]')).toHaveText('作者 · sasha birukoff');
  await expect(page.locator(`a[download="蓝色棱纹流动背景.html"]`)).toBeVisible();

  const sidebar = page.locator(`aside a[href="${href}"]`);
  await sidebar.hover();
  const floating = page.locator(`[data-sidebar-preview="${href}"]`);
  await expect(floating.locator('[data-scene-ready=true]')).toHaveCount(1);
  const rect = await floating.boundingBox();
  assert.equal(rect.width, 224);
  assert(Math.abs(rect.height - 168) < 2);
  await page.screenshot({ path: `${out}/sidebar-hover.png` });
  const floatingFrame = page.frameLocator(`[data-sidebar-preview="${href}"] iframe`);
  const initial = await floatingFrame.locator('.bfg-canvas').evaluate(n => n.toDataURL());
  await page.waitForTimeout(250);
  assert(await floatingFrame.locator('.bfg-canvas').evaluate(n => n.toDataURL()) !== initial, 'sidebar hover is animated');
  await page.mouse.move(1300, 20);
  await expect(floating).toHaveCount(0);
  await sidebar.focus();
  await expect(floating.locator('iframe')).toHaveCount(1);
  await page.evaluate(() => window.scrollBy(0, 160));
  await expect(floating).toHaveCount(0);

  // Sandboxed detail preview: map the local element box through its CSS scale.
  const iframe = page.locator('section[aria-label="Demo"] iframe');
  await iframe.scrollIntoViewIfNeeded();
  const detail = page.frameLocator('section[aria-label="Demo"] iframe');
  const outer = await iframe.boundingBox();
  const local = await detail.locator('.bfg-stage').evaluate(n => ({ rect: n.getBoundingClientRect().toJSON(), width: innerWidth }));
  const scale = outer.width / local.width;
  await page.mouse.click(outer.x + local.rect.width * scale / 2, outer.y + local.rect.height * scale / 2);
  await expect(detail.locator('.bfg-stage')).toHaveAttribute('aria-pressed', 'true');
  const stopped = await detail.locator('.bfg-canvas').evaluate(n => n.toDataURL());
  await page.waitForTimeout(150);
  assert(await detail.locator('.bfg-canvas').evaluate(n => n.toDataURL()) === stopped);
  await page.getByRole('button', { name: '重置演示', exact: true }).click();
  await expect(detail.locator('.bfg-stage')).toHaveAttribute('aria-pressed', 'false');

  // A real touch-enabled context exercises the click generated by a tap.
  const touch = await browser.newContext({ viewport: { width: 375, height: 700 }, hasTouch: true, isMobile: true });
  const mobile = await touch.newPage();
  await mobile.goto(base + `/motion/${slug}.html`);
  await mobile.locator('.bfg-stage[data-renderer=webgl]').waitFor();
  await mobile.touchscreen.tap(180, 350);
  await expect(mobile.locator('.bfg-stage')).toHaveAttribute('aria-pressed', 'true');
  await mobile.touchscreen.tap(180, 350);
  await expect(mobile.locator('.bfg-stage')).toHaveAttribute('aria-pressed', 'false');
  await touch.close();
  assert.deepEqual(errors, []);
  await fs.writeFile(`${out}/site-interactions.json`, JSON.stringify({ galleryHover: true, galleryFocus: true, hoverCleanup: true, sidebarAnimated: true, sidebarFocus: true, scrollCleanup: true, authorLink: true, noReferenceVideo: true, detailPause: true, reset: true, touch: true, errors }, null, 2));
  console.log('PASS blue-fluted-glass: gallery, sidebar, focus, cleanup, author, detail reset and touch');
} catch (error) {
  await page.screenshot({ path: `${out}/site-failure.png` });
  await fs.writeFile(`${out}/site-failure.json`, JSON.stringify({ error: String(error), url: page.url(), errors }, null, 2));
  throw error;
} finally {
  await browser.close();
}
